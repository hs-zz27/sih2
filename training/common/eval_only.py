"""Read-only re-measurement for the six heads that had no evaluator.

`docs/research/system-audit.md` **W16**: six of the seven specialist heads had
no way to be scored without destroying the number being checked. Every one of
`train_caption.py`, `train_grounding.py`, `train_change_mask.py`,
`track_a_full.py`, `train_optsar_fusion.py` and `train_change_caption.py`
runs its evaluation at the end of training and then writes `metrics.json`
into the checkpoint directory unconditionally - so the documented
"`--resume --epochs <already-trained>`" trick for reaching the eval block
also rewrote the published metrics in place. Only `change_vqa_v1` had a
genuine read-only evaluator (`evaluation/cdvqa_predict.py`).

`--eval-only` makes re-measurement safe. It is not a new capability: the same
model, data and metric code run, and the only thing that changes is where the
answer is allowed to land.

**Four writes have to be suppressed, not one.** `metrics.json` is the
obvious one. `run_metadata.json` is rewritten just as unconditionally and
carries the run provenance the trace ties back to. `train_caption.py` and
`train_grounding.py` also rewrite `vocab.json`, and `track_a_full.py` writes
`band_stats.json` - two of the twelve sidecars lost in the L29 incident and
regenerated by hand on 2026-08-31, so overwriting either from a
re-measurement would be that accident a second time. Under `--eval-only`
**nothing inside the checkpoint directory is written.**

The guards are wrappers rather than `if` blocks at each call site on purpose:
six trainers with one shared, tested rule is a smaller surface than six
hand-indented branches, and a future trainer gets the behaviour by calling
the same helper.

The vocabulary is *read* from the checkpoint directory in eval-only mode
rather than rebuilt from the training rows. Rebuilding happens to be
deterministic on today's data, but the checkpoint's embedding rows are sized
to the vocabulary saved beside it; reading it is the invariant, and
rebuilding merely appears to work until the data changes.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:  # pragma: no cover - typing only
    from training.common.checkpointing import TrainingState

# `training.common.checkpointing` imports torch at module scope, and torch is
# a TRAINING dependency that CI does not install. Importing it here would make
# this module - and so the tests for the guards in it - unimportable in the
# no-torch CI simulation, which is exactly where a regression in "does this
# write into the checkpoint directory?" would go unnoticed. The guards
# themselves are pure path-and-JSON logic and need nothing from torch, so the
# torch-backed helpers are imported inside the two functions that use them.


def add_eval_only_args(parser) -> None:
    """Add `--eval-only` and `--out` to a trainer's parser."""
    parser.add_argument(
        "--eval-only",
        action="store_true",
        help="score the checkpoint already in --ckpt-dir and write the "
             "metrics to --out. Trains nothing, and writes nothing inside "
             "--ckpt-dir: no checkpoint, no metrics.json, no "
             "run_metadata.json, no vocab.json.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="where --eval-only writes its metrics JSON. Required with "
             "--eval-only, and may not point inside --ckpt-dir.",
    )


def is_eval_only(args) -> bool:
    """Whether this run may not write into the checkpoint directory."""
    return bool(getattr(args, "eval_only", False))


def epochs_for(args) -> int:
    """Training epochs for this run - zero when scoring read-only."""
    return 0 if is_eval_only(args) else args.epochs


def resolve_metrics_path(args) -> Path:
    """Where this run is allowed to write its metrics.

    A normal training run keeps the existing behaviour and writes
    `<ckpt_dir>/metrics.json`. An `--eval-only` run must name an `--out`, and
    that path is refused if it lands anywhere inside the checkpoint
    directory - the whole point is that the artifact of record survives the
    measurement, and a caller who passes `--out checkpoints/caption/x.json`
    has not got that even though the flag is spelled correctly.
    """
    ckpt_dir = Path(args.ckpt_dir)
    if not is_eval_only(args):
        return ckpt_dir / "metrics.json"

    if args.out is None:
        sys.exit("--eval-only requires --out (it must not write into --ckpt-dir)")

    out = Path(args.out)
    try:
        inside = out.resolve().is_relative_to(ckpt_dir.resolve())
    except (OSError, ValueError):  # unresolvable path; treat as outside
        inside = False
    if inside:
        sys.exit(
            f"--out {out} is inside --ckpt-dir {ckpt_dir}. --eval-only exists "
            "so a re-measurement cannot overwrite the artifact of record; "
            "choose a path outside the checkpoint directory."
        )
    out.parent.mkdir(parents=True, exist_ok=True)
    return out


def write_metrics(args, metrics: dict) -> Path:
    """Write `metrics` wherever `resolve_metrics_path` allows."""
    path = resolve_metrics_path(args)
    path.write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    print(f"metrics -> {path}")
    return path


def resume_or_load_for_eval(args, model: Any, optimizer: Any = None) -> TrainingState:
    """Resume for training, or load the newest weights for scoring.

    An absent checkpoint under `--eval-only` is a hard exit rather than a
    silent evaluation of a randomly-initialised model, which would produce a
    plausible-looking number that means nothing.
    """
    if not is_eval_only(args):
        from training.common.checkpointing import maybe_resume

        return maybe_resume(
            args.ckpt_dir, model, optimizer, enabled=args.resume
        )[0]

    # Validate the destination HERE, not at the end, and before importing
    # anything torch-backed. Every trainer calls this before its eval block,
    # so a missing or badly-placed --out fails in a second rather than after
    # a scoring pass that then has nowhere to land.
    resolve_metrics_path(args)

    from training.common.checkpointing import (
        find_latest_checkpoint, load_checkpoint,
    )

    latest = find_latest_checkpoint(args.ckpt_dir)
    if latest is None:
        sys.exit(
            f"--eval-only: no ckpt_step_*.pt in {args.ckpt_dir}. There is "
            "nothing to score. (Some runs keep only `best.pt` or an adapter "
            "directory; this flag scores the step checkpoints.)"
        )
    state, _ = load_checkpoint(latest, model)
    print(f"--eval-only: scoring {latest.name} (step {state.step})")
    return state


def save_checkpoint_unless_eval(args, step: int, model, optimizer, **kwargs):
    """`save_checkpoint`, skipped entirely when scoring read-only."""
    if is_eval_only(args):
        return None
    from training.common.checkpointing import save_checkpoint

    return save_checkpoint(args.ckpt_dir, step, model, optimizer, **kwargs)


def write_run_metadata_unless_eval(args, metadata: dict):
    """`write_run_metadata`, skipped entirely when scoring read-only."""
    if is_eval_only(args):
        return None
    from training.common.checkpointing import write_run_metadata

    return write_run_metadata(args.ckpt_dir, metadata)


def write_sidecar_unless_eval(
    args, name: str, payload: dict, indent: int | None = None
) -> Path | None:
    """Write a JSON sidecar beside the checkpoint, unless scoring read-only.

    The sidecars are not incidental. `vocab.json` and `band_stats.json` are
    two of the twelve files lost in the L29 incident and regenerated by hand
    on 2026-08-31 - and `band_stats.json` is load-bearing at inference:
    without it `satquery/tools/landcover.py` standardises per image and the
    head asserts class 0 on every patch at 0.9 confidence, wrong every time.
    A re-measurement has no business rewriting either.
    """
    if is_eval_only(args):
        return None
    ckpt_dir = Path(args.ckpt_dir)
    ckpt_dir.mkdir(parents=True, exist_ok=True)
    path = ckpt_dir / name
    path.write_text(json.dumps(payload, indent=indent), encoding="utf-8")
    return path


def write_vocab_unless_eval(args, vocab: dict) -> Path | None:
    """Write `vocab.json` beside the checkpoint, unless scoring read-only."""
    return write_sidecar_unless_eval(args, "vocab.json", vocab)


def vocab_for(args, build) -> dict:
    """The saved vocabulary when scoring read-only, else a freshly built one.

    `build` is a zero-argument callable so the training-row scan is not paid
    for when the saved vocabulary is going to be used instead.
    """
    if is_eval_only(args):
        path = Path(args.ckpt_dir) / "vocab.json"
        if path.exists():
            return json.loads(path.read_text(encoding="utf-8"))
        print(
            f"--eval-only: no vocab.json in {args.ckpt_dir}; rebuilding it "
            "from the training rows. If the checkpoint was trained against a "
            "different vocabulary its embedding rows will not line up.",
            file=sys.stderr,
        )
    return build()
